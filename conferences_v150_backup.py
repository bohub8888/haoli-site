def display(e: dict) -> str:
    """生成期写入全量池 / 网页日历 / 小组件的名称。"""
    return f"{e.get('tag', PREFIX)} · {e['name']}"


def for_year(year: int) -> list[dict]:
    return [e for e in ENTRIES if e["date"].startswith(f"{year}-")]


def validate() -> list[str]:
    """构建期闸门：任何一条不合格即返回错误，让 build.py 直接失败。"""
    errs: list[str] = []
    seen: set[tuple[str, str]] = set()
    for e in ENTRIES:
        tag = f"{e['date']} {e['name']}"
        try:
            d0 = dt.date.fromisoformat(e["date"])
            d1 = dt.date.fromisoformat(e["end"])
        except ValueError:
            errs.append(f"日期非法：{tag}")
            continue
        if d1 < d0:
            errs.append(f"会期结束早于开幕：{tag}")
        key = (e["date"], e["name"])
        if key in seen:
            errs.append(f"同日同名重复：{tag}")
        seen.add(key)

        name, pub, note = e["name"], e.get("public", ""), e.get("note", "")
        if not all((name, e["place"], e["source"], e["url"], pub, note)):
            errs.append(f"缺字段：{tag}")
        if not e["url"].startswith(("http://", "https://")):
            errs.append(f"来源链接无效：{tag}")
        if e["grade"] not in ("A", "B"):
            errs.append(f"来源等级不合规：{tag}")
        if e["scope"] not in ("world", "cn"):
            errs.append(f"scope 不合规：{tag}")
        if "·" in name or name.startswith((PREFIX, EXPO_PREFIX)):
            errs.append(f"名称自带分隔符或前缀：{tag}")
        if re.search(r"20\d{2}年", name):
            errs.append(f"名称写死年份：{tag}")

        # 内容红线：会议名 / 地点 / 对外说明都不得出现议题性、主权性、战犯侵略表述
        for w in _BAN:
            if w in name or w in pub:
                errs.append(f"会议层内容红线命中「{w}」：{tag}")
        # 一个中国：港澳台必须带「中国」前缀
        for field in (name, e["place"], pub):
            hit = _SOVEREIGN.search(field)
            if hit:
                errs.append(f"违反一个中国表述「{hit.group(1)}」：{tag}")
        # 对外说明不得混入内部术语或裸 URL
        for w in _INTERNAL_TERMS:
            if w in pub:
                errs.append(f"对外说明混入内部术语「{w}」：{tag}")
        if "http" in pub:
            errs.append(f"对外说明含裸 URL：{tag}")
    return errs


def report() -> dict:
    """生成期实测报告用：按年、按源头统计。"""
    out: dict[str, dict] = {}
    for y in (2026, 2027):
        rows = for_year(y)
        out[str(y)] = {"total": len(rows), "days": len({e["date"] for e in rows})}
    return out


