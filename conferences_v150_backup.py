"""世界级 / 国家级会议与活动策展库 —— v1.49 新增的独立数据层。

为什么是「策展库」而不是抓取器
--------------------------------
调研结论：不存在一个能自动同步「世界级 + 国家级会议」的开放 API 或 ICS 订阅。
APEC / G20 / UNFCCC / 中国政府网 / 轮值主席国官网都只提供网页日历或公告，
且会期会临时改期、改地点、取消。因此沿用 curated.py 的既有治理方式：
**官方源逐条核源 → 人工策展 → 生成期闸门**，不写自动抓取。

准入闸门（缺一即删，validate() 会拦）
--------------------------------------
  1. 国家 / 政府间组织 / 国家级机构 / 国际单项体育联合会主办或承办的会议、
     世博会、综合运动会与旗舰赛事；以及 S8「全球旗舰行业展」——由主办方
     官网公布确切会期、具全球行业标杆地位的展览（CES / MWC / IFA / Web Summit…）。
     企业发布会、巡回赛分站、地方展销会一律不收。
  2. 官方已公布**确切开幕日期**。「预计 / 待定 / 下旬 / 11 月某周」一律不收，
     例如 APEC 2027 越南只公布「11 月领导人周」、金砖 2027 会期未定，均不入库。
     **但绝不能用个别源头未定档，推断整年没有已定档活动**：2027 的 FIFA /
     World Athletics / FISU / ITTF / ITU / BIE / UN ESCAP / AFC 与各展会官网
     都已白纸黑字定档（v1.50 复核补录 27 条，见文件末尾 CHANGELOG）。
  3. 只收**开幕日 1 条**，会期其余天不展开（避免像 2027 女足世界杯那样逐日刷屏）。
  4. 只收「会议名称 + 日期 + 地点」，**不收议题、宣言、公报、参会方表述**——
     这是政治安全的关键：会议本身中性，议题才可能踩线。
  5. 港澳台一律按一个中国原则写「中国香港 / 中国澳门 / 中国台湾」，
     绝不作为国家出现；R2 主权表述红线对会议层同样生效。
  6. 名称用官方公布过的全称或官方媒体用过的简称，不自造短名。
  7. 生成名前缀按形态区分：会议 / 赛事 / 世博用「会议 · 」，行业展用「展会 · 」
     （App 按「·」拆两列，前缀落在右列成为类型标签，左列是活动名）。

源头分层（S1–S7，条数见模块底部 REPORT）
----------------------------------------
  S1 APEC        apec.org/engage-with-us/events-calendar + 外交部 + 中国政府网
  S2 G20         g20.org/events/
  S3 联合国       unfccc.int 官方通知、un.org 全球会议日历
  S4 中国官方     gov.cn / mfa.gov.cn / 商务部重点展会目录 / 各展会官网 / 政协网
  S5 多边峰会     轮值主席国官网、新华社、人民网
  S6 高规格论坛   博鳌官网、世界互联网大会官网
  S7 全球运动会   人民日报海外版赛历、新华社、各国际单项体育联合会官网
  S8 旗舰行业展   CES / GSMA / 汉诺威 / IFA / Web Summit 等主办方官网

更新节奏：每年 Q4 扫下一年官方定档 → 逐条核源 → append → 本文件 CHANGELOG 记一笔。
未定档的年份宁可空着，也不猜日期。

字段
----
  date     开幕日（唯一落点，YYYY-MM-DD）
  end      会期结束日（仅供 public 叙述，不展开成逐日条目）
  name     显示名（不含「会议 · 」前缀，生成期补）
  scope    world / cn，决定元数据 scope
  place    举办地（对外可见）
  source   来源标题
  url      来源链接（A/B 级）
  grade    来源等级 A / B
  public   对外说明，可进网站当日详情与 ICS DESCRIPTION；禁内部术语、禁裸 URL
  note     内部备注，只进依据库与生成期报告，绝不外露
"""

