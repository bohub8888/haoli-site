def off_dates(year: int) -> set[dt.date]:
    """该年官方放假区间展开后的全部日期（含连休里的周末）。"""
    out: set[dt.date] = set()
    for a, b, _n, _d in CN_OFFICIAL.get(year, []):
        d = a
        while d <= b:
            out.add(d)
            d += dt.timedelta(days=1)
    return out


def workday_dates(year: int) -> set[dt.date]:
    """该年因调休需要上班的周末日期。"""
    return {d for d, _n in CN_WORKDAYS.get(year, [])}


def covered_years() -> list[int]:
    return sorted(set(CN_OFFICIAL) | set(CN_WORKDAYS))
