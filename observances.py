class Obs(NamedTuple):
    date: dt.date
    name: str
    w: int
    scope: str      # "cn" | "world"
    cat: str        # 法定/传统/纪念/职业/健康/环境/文化/社会/消费/民俗/体育/国际
    note: str       # 全称，可能为空


def nth_weekday(year: int, month: int, nth: int, weekday: int) -> dt.date | None:
    """取某月第 nth 个星期 weekday 的日期；nth=-1 取最后一个。"""
    if nth > 0:
        first = dt.date(year, month, 1)
        delta = (weekday - first.weekday()) % 7
        d = first + dt.timedelta(days=delta + 7 * (nth - 1))
        return d if d.month == month else None
    # 最后一个：从月末往前找
    nxt = dt.date(year + (1 if month == 12 else 0), 1 if month == 12 else month + 1, 1)
    last = nxt - dt.timedelta(days=1)
    delta = (last.weekday() - weekday) % 7
    return last - dt.timedelta(days=delta)


def solar_of(year: int, terms: list[tuple[dt.date, str]] | None = None) -> list[Obs]:
    """固定日期 + 浮动日期（+ 可选的节气挂靠节日），返回 Obs 列表。"""
    out: list[Obs] = []
    for m, d, name, w, scope, cat in CN_SOLAR:
        out.append(Obs(dt.date(year, m, d), name, w, scope, cat, NOTE.get(name, "")))
    for m, nth, wd, name, w, scope, cat in CN_FLOAT:
        d = nth_weekday(year, m, nth, wd)
        if d:
            out.append(Obs(d, name, w, scope, cat, NOTE.get(name, "")))
    for d, term in terms or []:
        for name, w, scope, cat in TERM_FEST.get(term, []):
            out.append(Obs(d, name, w, scope, cat, NOTE.get(name, "")))
    return out


def index() -> dict[str, Obs]:
    """名称 → 记录（不含年份，用于校验、查权重与「这条算不算节日」）。

    节气挂靠的节日（丰收节）没有固定公历日期，solar_of(2026) 不带节气表算不出来，
    这里补进去，否则它们在 Apk 数据里会退化成普通固定节日（kind=fix）。
    """
    out: dict[str, Obs] = {o.name: o for o in solar_of(2026)}
    for items in TERM_FEST.values():
        for name, w, scope, cat in items:
            out.setdefault(name, Obs(dt.date(2026, 1, 1), name, w, scope, cat, NOTE.get(name, "")))
    return out


OBS_BY_NAME: dict[str, Obs] = index()


def names() -> set[str]:
    return set(OBS_BY_NAME)


