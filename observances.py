"""中国纪念日 / 宣传日 / 国际日 总表 —— 官网 ics、APK 内置数据、全球日历的唯一来源。

为什么单独一个文件：
  这张表原来在 build.py 和 haoli-apk/tools/gen_apk_data.py 里各抄了一份，
  两份一漂移就会出现「官网有、App 没有」或者反过来。现在两边都 import 这里。

2026-11-09 重构（v2）：从「一堆元组」改成「带字段的记录」。
  老结构只有 (月, 日, 名称, 权重) 四个字段，其余信息全靠代码里的 if 去猜：
    - build.py 用「名字是否以『世界/国际』开头」决定要不要进全球日历；
    - gen_apk_data.py 用一份手写的 OBSERVANCE 集合决定这条算不算「纪念日」。
  两条规则都不是数据，是会腐化的副本。实证：OBSERVANCE 里写的是旧名
  「消防宣传日」，表里早已改名「全国消防日」，于是 11-09 那天这条被降级成
  普通固定节日（kind=fix），权重靠名字兜底才没丢——分类却已经错了。
  现在把「范围 scope」「类别 cat」写进数据本身，代码不再猜。

字段：
  公历   (月, 日, 名称, 权重, scope, cat)
  浮动   (月, 第几个, 星期几, 名称, 权重, scope, cat)   第几个 -1 = 当月最后一个
         星期：0=周一 … 6=周日

  scope：
    "world" = 本身是国际日/世界日，全球通用名称，全球日历里原样出现
    "cn"    = 中国专属（纪念日、职业节、洋节、电商节）。中国日历全量收录；
              全球日历只收 w≥2 的，加「中国 · 」前缀，保证「世界的数据包含中国」

  cat：法定 / 传统 / 纪念 / 职业 / 健康 / 环境 / 文化 / 社会 / 消费 / 民俗 / 体育 / 国际

  权重 weight：
    3 = 法定假日 / 传统大节 / 节气 / 国家级重大纪念日 —— 小组件倒计时会算
    2 = 重要的国家宣传日、行业节日、影响日常行为的大促 —— 小组件倒计时会算
    1 = 一般国际日、小众纪念 —— 只进 App 与日历，不占小组件倒计时
        （否则会出现「世界厕所日 明天」把「小雪 3 天后」挤掉）

命名纪律：
  显示名尽量 ≤ 6 字，全称放 NOTE。2×1 小组件半格只有约 48dp，
  名字一长就得降字号，降到地板还放不下才截字加省略号。
"""

