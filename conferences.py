def for_year(year: int) -> list[dict]:
    return [e for e in ENTRIES if e["date"].startswith(f"{year}-")]


def series_of(name: str) -> str | None:
    for prefix, key in _SERIES.items():
        if name.startswith(prefix):
            return key
    return None


def validate() -> list[str]:
    """构建期闸门：任何一条不合格即返回错误，让 build.py 直接失败。"""
    errs: list[str] = []
    seen: set[tuple[str, str]] = set()
    series_count: dict[tuple[str, str], list[str]] = {}
    for e in ENTRIES:
        tag = f"{e['date']} {e['name']}"
        try:
            d0 = dt.date.fromisoformat(e["date"])
            d1 = dt.date.fromisoformat(e["end"])
        except ValueError:
            errs.append(f"日期非法：{tag}")
            continue
        if d1 < d0:
            errs.append(f"会期结束早于开幕：{tag}")
        if (d1 - d0).days > 200:
            errs.append(f"会期超过 200 天，疑似把整个展期当会期：{tag}")
        key = (e["date"], e["name"])
        if key in seen:
            errs.append(f"同日同名重复：{tag}")
        seen.add(key)

        name, pub, note = e["name"], e.get("public", ""), e.get("note", "")
        if not all((name, e["place"], e["source"], e["url"], pub, note)):
            errs.append(f"缺字段：{tag}")
        if not e["url"].startswith(("http://", "https://")):
            errs.append(f"来源链接无效：{tag}")
        if e["grade"] not in ("A", "B"):
            errs.append(f"来源等级不合规：{tag}")
        if e.get("cert", "official") not in ("official", "open"):
            errs.append(f"定档状态不合规：{tag}")
        if e.get("cert") == "open" and "按历届" not in note:
            errs.append(f"cert=open 但 note 未写会期依据：{tag}")
        if e["scope"] not in ("world", "cn"):
            errs.append(f"scope 不合规：{tag}")
        if "·" in name or name.startswith((PREFIX, EXPO_PREFIX)):
            errs.append(f"名称自带分隔符或前缀：{tag}")
        if re.search(r"20\d{{2}}年", name):
            errs.append(f"名称写死年份：{tag}")

        # 附属会闸门：收了筹备会 / 部长会 / 配套会就报错
        hit_sub = [w for w in _SUB_PATTERNS if w in name]
        if hit_sub:
            errs.append(f"附属会 / 筹备会不入库（命中「{hit_sub[0]}」）：{tag}")

        # 一个系列一年只留一条主会
        s = series_of(name)
        if s:
            series_count.setdefault((e["date"][:4], s), []).append(name)

        # 内容红线：会议名 / 地点 / 对外说明都不得出现议题性、主权性、战犯侵略表述
        for w in _BAN:
            if w in name or w in pub:
                errs.append(f"会议层内容红线命中「{w}」：{tag}")
        # 一个中国：港澳台必须带「中国」前缀
        for field in (name, e["place"], pub):
            hit = _SOVEREIGN.search(field)
            if hit:
                errs.append(f"违反一个中国表述「{hit.group(1)}」：{tag}")
        # 对外说明不得混入内部术语或裸 URL
        for w in _INTERNAL_TERMS:
            if w in pub:
                errs.append(f"对外说明混入内部术语「{w}」：{tag}")
        if "http" in pub:
            errs.append(f"对外说明含裸 URL：{tag}")

    for (year, s), names in series_count.items():
        if len(names) > 1:
            errs.append(f"{year} 年 {s} 收了 {len(names)} 条主会（只允许 1 条）：{names}")
    return errs


def report() -> dict:
    """生成期实测报告用：按年、按标签、按来源等级统计。"""
    out: dict[str, dict] = {}
    for y in (2026, 2027):
        rows = for_year(y)
        out[str(y)] = {
            "total": len(rows),
            "days": len({e["date"] for e in rows}),
            "会议": sum(1 for e in rows if e["tag"] == "会议"),
            "展会": sum(1 for e in rows if e["tag"] == "展会"),
            "A": sum(1 for e in rows if e["grade"] == "A"),
            "B": sum(1 for e in rows if e["grade"] == "B"),
            "pending": len(WATCHLIST),
        }
    return out


def watch_report(today: dt.date | None = None) -> list[dict]:
    """观察名单按预计日期排序，供每月核对脚本打印。"""
    today = today or dt.date.today()
    rows = []
    for w in WATCHLIST:
        d = dt.date.fromisoformat(w["date_hint"])
        rows.append(dict(w, days_left=(d - today).days))
    return sorted(rows, key=lambda x: x["date_hint"])


