def is_industry(name: str) -> bool:
    """该条目是否属 S9 行业旗舰层（仅用于分层统计与标注，不参与任何过滤）。

    全端一致口径（2026-11-19 定档）：数据层是唯一事实源，有这条数据所有端都展示，
    展现层不做二次删减。准入闸门是唯一的门槛，通过即全端同步。

    兼容两种写法：裸名「世界机器人大会」与带前缀的生成名「会议 · 世界机器人大会」。
    """
    bare = name
    for pre in (f"{PREFIX} · ", f"{EXPO_PREFIX} · "):
        if bare.startswith(pre):
            bare = bare[len(pre):]
            break
    return bare in INDUSTRY



