_INTERNAL_TERMS = ("anchor", "推算", "入库", "闸门", "不写死", "不自造", "按诞辰当日",
                   "写死", "自动算", "生成期", "scope=", "cat=")


def for_year(year: int) -> list[dict]:
    """返回该年的策展条目（含自动计算的周年，绝不写死在名称里）。"""
    out = []
    for e in ENTRIES:
        item = dict(e)
        item["year"] = year
        item["anniversary"] = (year - e["anchor"]) if e.get("anchor") else None
        out.append(item)
    return out


def by_mmdd() -> dict[str, dict]:
    return {e["mmdd"]: e for e in ENTRIES}


def validate() -> list[str]:
    """构建期闸门：任何一条不合格即返回错误，由 build.py 让构建失败。"""
    errs: list[str] = []
    seen = set()
    for e in ENTRIES:
        tag = f"{e['mmdd']} {e['name']}"
        if e["mmdd"] in seen:
            errs.append(f"重复日期：{tag}")
        seen.add(e["mmdd"])
        if not (e["name"] and e["kind"] and e["sources"]):
            errs.append(f"缺字段：{tag}")
        if not any(lv in ("A", "B") for _t, _u, lv in e["sources"]):
            errs.append(f"无 A/B 级来源：{tag}")
        for _t, url, _lv in e["sources"]:
            if not url.startswith(("http://", "https://")):
                errs.append(f"来源链接无效：{tag} -> {url}")
        if "（19" in e["name"] or "（20" in e["name"]:
            errs.append(f"名称写死了年份：{tag}")

        # v1.46：对外说明必须存在、干净、且不含内部术语或裸 URL。
        pub = e.get("public", "")
        if not pub:
            errs.append(f"缺对外说明 public：{tag}")
        for w in _INTERNAL_TERMS:
            if w in pub:
                errs.append(f"对外说明混入内部术语「{w}」：{tag}")
        if "http" in pub:
            errs.append(f"对外说明含裸 URL：{tag}")
        if not e.get("note"):
            errs.append(f"缺内部备注 note（依据库要用）：{tag}")
    return errs


